// Gera o documento de revisão para a responsável técnica a partir do que está no código (assim o texto revisado é exatamente o que o sistema usa).
import { writeFileSync, mkdirSync } from "node:fs";
import { ESCALAS } from "./src/lib/escalas/definicoes";
import * as D from "./src/lib/diario/catalogo";
import { MODELOS_SISTEMA } from "./src/lib/formularios/modelos";
import { MODELOS, PROFISSOES } from "./src/lib/prontuario/modelos";

const L: string[] = [];
const p = (s = "") => L.push(s);
const lista = (o: D.Opcao[]) => o.map((x) => `- ${x.rotulo}`).join("\n");

p("# Pacote de revisão para a Letícia");
p();
p("**Para:** Letícia, psicóloga responsável técnica. **De:** equipe de desenvolvimento do MentEssence.");
p();
p("Este documento reúne **todos os textos clínicos que o sistema mostra a pacientes e profissionais** e que precisam da sua leitura antes de usarmos com pacientes reais. Nada aqui foi publicado ainda. Para cada bloco, o que pedimos é simples: **aprovar, ou escrever o ajuste** (o texto que você mandar entra como está).");
p();
p("Como marcar: ao lado de cada bloco há `[ ] Aprovado` e `[ ] Ajustar`. Se for ajustar, escreva a mudança logo abaixo.");
p();
p("## O que mais importa (leia primeiro)");
p();
p("1. **Aviso de segurança** do Diário e o comportamento do alerta de risco (seção 3). É o ponto mais sensível.");
p("2. **Escalas** (seção 1): conferir se a versão em português e as faixas de interpretação são as que você usa.");
p("3. **Textos do Diário** (seção 2): linguagem de todas as perguntas que o paciente responde no dia a dia.");
p("4. Anamneses (seção 4) e modelos de evolução (seção 5).");
p();
p("Regras do sistema que valem para tudo: o resultado das escalas é **triagem, não diagnóstico**; o **paciente nunca vê a pontuação**; só o profissional responsável (ou o administrador) lê as respostas.");
p();
p("---");
p();
p("## 1. Escalas de triagem");
p();
p("O paciente recebe um link, responde no celular e o profissional vê a pontuação e a faixa. Em todas, conferir: **fonte e versão**, **enunciado**, **opções de resposta**, **faixas**.");
p();
ESCALAS.forEach((e, n) => {
  p(`### 1.${n + 1} ${e.nome} (${e.sigla})`);
  p();
  p(`- **Mede:** ${e.construto}`);
  p(`- **Uso:** ${e.uso}`);
  p(`- **Tempo:** ${e.tempo}. **Repetição sugerida:** ${e.frequenciaSugerida}`);
  p(`- **Fonte indicada no sistema:** ${e.fonte}`);
  p(`- **Instrução mostrada ao paciente:** ${e.instrucao}`);
  p(`- **Opções de resposta (padrão):** ${e.opcoes.map((o) => `${o.valor} = ${o.rotulo}`).join("; ")}`);
  if (e.multiplicadorTotal) p(`- **Cálculo:** soma das respostas × ${e.multiplicadorTotal}`);
  if (e.faixasTotal) {
    let ini = 0;
    const f = e.faixasTotal.map((x) => { const t = `${ini} a ${x.ate}: ${x.rotulo}`; ini = x.ate + 1; return t; });
    p(`- **Faixas do total:** ${f.join(" | ")}`);
  }
  (e.subescalas ?? []).forEach((s) => {
    const its = e.itens.filter((i) => i.subescala === s.chave).map((i) => i.id).join(", ");
    let ini = 0;
    const f = s.faixas?.map((x) => { const t = `${ini} a ${x.ate}: ${x.rotulo}`; ini = x.ate + 1; return t; }).join(" | ");
    p(`- **Grupo ${s.rotulo}** (perguntas ${its}${s.multiplicador ? `; valor × ${s.multiplicador}` : ""})${f ? `: ${f}` : " (só soma, sem faixa)"}`);
  });
  if (e.pontosDeCorte?.length) p(`- **Linhas de corte no gráfico:** ${e.pontosDeCorte.join(", ")}`);
  if (e.itensCriticos?.length) p(`- **Alerta de risco:** qualquer resposta acima de 0 na(s) pergunta(s) ${e.itensCriticos.join(", ")} avisa o profissional.`);
  if (e.itemFuncional) p(`- **Pergunta final (funcionalidade):** ${e.itemFuncional.texto}`);
  p();
  p("**Perguntas:**");
  p();
  e.itens.forEach((i) => {
    p(`${i.id}. ${i.texto}`);
    if (i.opcoes) p(`   - opções desta pergunta: ${i.opcoes.map((o) => `${o.valor} = ${o.rotulo}`).join("; ")}`);
  });
  p();
  p("`[ ] Aprovado`   `[ ] Ajustar` → ");
  p();
});
p("---");
p();
p("## 2. Diário emocional do paciente");
p();
p(`Versão do catálogo: ${D.VERSAO_CATALOGO}. O paciente registra uma emoção por vez, em etapas curtas. Os textos abaixo foram reescritos com linguagem própria; as emoções são agrupadas em famílias.`);
p();
p("### 2.1 Famílias de emoções e frases de apoio");
p();
D.FAMILIAS.forEach((f) => { p(`**${f.rotulo}**: ${f.descricao}`); p(); f.apoio.forEach((a) => p(`- apoio: "${a}"`)); p(); });
p("### 2.2 Emoções oferecidas");
p();
D.FAMILIAS.forEach((f) => p(`- **${f.rotulo}:** ${D.EMOCOES.filter((e) => e.familia === f.chave).map((e) => e.rotulo).join(", ")}`));
p();
p("### 2.3 Onde estava / o que estava acontecendo"); p(); p(lista(D.CONTEXTOS)); p();
p("### 2.4 O que fez primeiro"); p(); p(lista(D.PRIMEIRAS_ACOES)); p();
p("### 2.5 O que ajudou"); p(); p(lista(D.ACOES_QUE_AJUDARAM)); p();
p("### 2.6 Quanto ajudou"); p(); p(lista(D.AJUDOU)); p();
p("### 2.7 O que pesou no dia (etapa opcional)"); p(); p(lista(D.PESOS_DO_DIA)); p();
p("### 2.8 Vontades difíceis (etapa opcional)"); p(); p("O que sentiu vontade de fazer:"); p(); p(lista(D.IMPULSOS)); p(); p("E o que fez:"); p(); p(lista(D.ACOES_DO_IMPULSO)); p();
p("### 2.9 Frases de fecho"); p(); p(lista(D.FECHAMENTOS)); p();
p("`[ ] Aprovado`   `[ ] Ajustar` → ");
p();
p("---");
p();
p("## 3. Aviso de segurança e alerta de risco");
p();
p("**Texto mostrado ao paciente** quando registra uma emoção de sofrimento (família baixa, distante ou inquieta) com intensidade 4 ou 5:");
p();
p(`> **Aviso padrão (todo registro):** ${D.AVISO_SEGURANCA.curto}`);
p();
p(`> **Aviso com sofrimento intenso:** ${D.AVISO_SEGURANCA.intenso}`);
p();
p("**Como funciona o alerta:**");
p();
p("- **Diário:** o sistema só mostra o aviso ao paciente. **Hoje o profissional NÃO recebe alerta** por registro de sofrimento intenso (ele só vê a intensidade na ficha, quando abre).");
p("- **Escalas:** qualquer resposta acima de 0 em pergunta crítica (PHQ-9, pergunta 9; DASS-21, pergunta 21) marca a escala com \"atenção\" na ficha do profissional e mostra ao paciente, ao concluir, a mensagem de cuidado com os contatos de ajuda.");
p("- Contatos citados: **CVV 188** (24 h) e **SAMU 192**.");
p();
p("Perguntas para você:");
p();
p("1. O texto do aviso está adequado e acolhedor? Falta algum contato (CAPS, UPA da região)?");
p("2. Intensidade 4 ou 5 em emoções de sofrimento é um bom critério para mostrar o aviso, ou prefere só 5?");
p("3. O profissional deve ser avisado na hora (e-mail ou aviso no painel; **ainda não existe**) quando o paciente registrar sofrimento intenso, ou basta ver na ficha? Recomendamos construir esse aviso antes de usar com pacientes reais.");
p();
p("`[ ] Aprovado`   `[ ] Ajustar` → ");
p();
p("---");
p();
p("## 4. Anamneses e formulários");
p();
p("O profissional pode pedir ao paciente por link ou preencher na sessão. Cada modelo pode ser copiado e editado.");
p();
MODELOS_SISTEMA.forEach((m, n) => {
  p(`### 4.${n + 1} ${m.nome}`);
  p();
  p(`${m.descricao} (para: ${m.paraQuem.join(", ")})`);
  p();
  m.perguntas.forEach((q, i) => {
    const extra = q.opcoes ? ` — opções: ${q.opcoes.join(" / ")}` : q.tipo === "escala" ? ` — escala de ${q.min} a ${q.max}` : q.tipo === "sim_nao" ? " — sim ou não" : q.tipo === "data" ? " — data" : "";
    p(`${i + 1}. ${q.rotulo}${q.obrigatoria ? " *(obrigatória)*" : ""}${extra}${q.ajuda ? ` _(dica: ${q.ajuda})_` : ""}`);
  });
  p();
  p("`[ ] Aprovado`   `[ ] Ajustar` → ");
  p();
});
p("---");
p();
p("## 5. Modelos de evolução (registro da sessão)");
p();
p("Cada sessão é registrada em um modelo. Há também um campo de **anotações privadas** que só quem escreveu consegue ler. Conferir nome, campos e dicas de preenchimento.");
p();
MODELOS.forEach((m, n) => {
  p(`### 5.${n + 1} ${m.rotulo}`);
  p();
  p(m.descricao);
  p();
  m.campos.forEach((c) => p(`- **${c.rotulo}**${c.lista ? " (lista)" : ""}: ${c.dica}`));
  p();
  p("`[ ] Aprovado`   `[ ] Ajustar` → ");
  p();
});
p("### 5.x Quais modelos cada profissão vê");
p();
PROFISSOES.forEach((pr) => p(`- **${pr.rotulo}** (${pr.registro}): ${pr.modelos.map((c) => MODELOS.find((m) => m.chave === c)?.rotulo ?? c).join(", ")}`));
p();
p("---");
p();
p("## 6. Pontos que dependem de você ou do jurídico");
p();
p("- Texto de **consentimento para gravação** de videochamada (ainda não definido; precisa de revisão jurídica e sua).");
p("- Confirmar se podemos usar as escalas acima **sem pedir permissão** aos autores (indicamos uso livre; a confirmação é sua).");
p("- Perguntas já em aberto de outros instrumentos: BRIEF-2, FDT e SRS-2 (lista separada).");
p();
mkdirSync("../../docs/revisao-leticia", { recursive: true });
writeFileSync("../../docs/revisao-leticia/PACOTE-REVISAO.md", L.join("\n") + "\n", "utf8");
console.log("linhas:", L.length);
